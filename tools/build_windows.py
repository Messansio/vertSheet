"""Builds the Windows program and its installation wizard.

    python tools/build_windows.py              # tests, program, installer, self-test
    python tools/build_windows.py --no-tests   # skip the unit tests
    python tools/build_windows.py --no-selftest

Results in dist/:

    vertSheet-Setup-<version>.exe       the installation wizard (one file)
    vertSheet-<version>-portable.zip    the program without installation:
                                        unzip, then run vertSheet.exe (window)
                                        or vertsheet-cli.exe (command line)

Intermediate files go to %TEMP%\vertSheet-build (outside the project,
which may be in a synced folder); PyInstaller is installed automatically into
its "venv" folder, nothing is added to the system Python. The self-test installs the freshly built setup into a
sandbox (registry under HKCU\\Software\\vertSheet-selftest, files and shortcuts
in %TEMP%\\vertsheet-selftest), runs the installed program and uninstalls it.
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIST = os.path.join(ROOT, "dist")
# intermediate files live on the local disk, outside the project: the project
# may sit in a synced folder (OneDrive), which locks freshly written folders.
# (%TEMP% rather than %LOCALAPPDATA%: the Microsoft Store Python silently
# redirects its writes to %LOCALAPPDATA% into its own package folder.)
BUILD = os.path.join(tempfile.gettempdir(), "vertSheet-build")
VENV = os.path.join(BUILD, "venv")
ASSETS = os.path.join(ROOT, "assets")
APP_DIR = os.path.join(BUILD, "dist", "vertSheet")
ASSET_FILES = ("vertsheet.ico", "vertsheet-32.png", "vertsheet-64.png", "vertsheet-128.png")


def rmtree(path: str, move_aside: bool = True) -> None:
    """Delete a folder, retrying: OneDrive and virus scanners briefly lock
    folders that were just written. As a last resort the folder is moved
    aside into build/trash so that the build can go on."""
    for _ in range(20 if move_aside else 4):
        if not os.path.exists(path):
            return
        shutil.rmtree(path, ignore_errors=True)
        if not os.path.exists(path):
            return
        time.sleep(0.5)
    if not move_aside:
        return
    trash = os.path.join(BUILD, "trash", f"{os.path.basename(path)}-{int(time.time())}")
    os.makedirs(os.path.dirname(trash), exist_ok=True)
    os.replace(path, trash)


def step(msg: str) -> None:
    print(f"\n=== {msg}", flush=True)


def run(cmd, **kw) -> subprocess.CompletedProcess:
    print("  $", " ".join(f'"{c}"' if " " in str(c) else str(c) for c in cmd), flush=True)
    return subprocess.run(cmd, check=True, **kw)


def version() -> str:
    with open(os.path.join(ROOT, "vertsheet", "__init__.py"), encoding="utf-8") as fh:
        m = re.search(r'__version__\s*=\s*"([^"]+)"', fh.read())
    return m.group(1) if m else "0.0.0"


def build_python() -> str:
    py = os.path.join(VENV, "Scripts", "python.exe")
    if not os.path.isfile(py):
        step(f"creating the build environment ({VENV})")
        run([sys.executable, "-m", "venv", VENV])
    probe = subprocess.run([py, "-m", "PyInstaller", "--version"], capture_output=True, text=True)
    if probe.returncode != 0:
        step("installing PyInstaller into the build environment")
        run([py, "-m", "pip", "install", "--disable-pip-version-check", "-q", "pyinstaller"])
    return py


def version_file(path: str, ver: str, description: str, filename: str) -> str:
    nums = [int(x) for x in re.findall(r"\d+", ver)[:3]] + [0, 0, 0]
    t = tuple(nums[:3] + [0])
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(f"""VSVersionInfo(
  ffi=FixedFileInfo(filevers={t}, prodvers={t}, mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'vertSheet'),
      StringStruct('FileDescription', {description!r}),
      StringStruct('FileVersion', {ver!r}),
      StringStruct('InternalName', {os.path.splitext(filename)[0]!r}),
      StringStruct('OriginalFilename', {filename!r}),
      StringStruct('ProductName', 'vertSheet'),
      StringStruct('ProductVersion', {ver!r})])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
""")
    return path


APP_SPEC = r'''# generated by tools/build_windows.py - do not edit
import os
root = {root!r}
datas = [(os.path.join(root, "assets", f), "assets") for f in {assets!r}]
excludes = ["unittest", "pydoc_data", "lib2to3", "setuptools", "pip", "test"]
a_gui = Analysis([os.path.join(root, "installer", "entry_gui.py")], pathex=[root], datas=datas,
                 excludes=excludes)
a_cli = Analysis([os.path.join(root, "installer", "entry_cli.py")], pathex=[root], datas=datas,
                 excludes=excludes)
pyz_gui = PYZ(a_gui.pure)
pyz_cli = PYZ(a_cli.pure)
exe_gui = EXE(pyz_gui, a_gui.scripts, [], exclude_binaries=True, name="vertSheet", console=False,
              icon={ico!r}, version={ver_gui!r}, upx=False)
exe_cli = EXE(pyz_cli, a_cli.scripts, [], exclude_binaries=True, name="vertsheet-cli", console=True,
              icon={ico!r}, version={ver_cli!r}, upx=False)
coll = COLLECT(exe_gui, a_gui.binaries, a_gui.datas, exe_cli, a_cli.binaries, a_cli.datas,
               strip=False, upx=False, name="vertSheet")
'''


def build_app(py: str, ver: str) -> None:
    step("building the program")
    os.makedirs(BUILD, exist_ok=True)
    ver_gui = version_file(os.path.join(BUILD, "version_gui.txt"), ver,
                           "vertSheet - vertical piano sheet music", "vertSheet.exe")
    ver_cli = version_file(os.path.join(BUILD, "version_cli.txt"), ver,
                           "vertSheet command line", "vertsheet-cli.exe")
    spec = os.path.join(BUILD, "vertSheet.spec")
    with open(spec, "w", encoding="utf-8") as fh:
        fh.write(APP_SPEC.format(root=ROOT, assets=ASSET_FILES, ico=os.path.join(ASSETS, "vertsheet.ico"),
                                 ver_gui=ver_gui, ver_cli=ver_cli))
    rmtree(os.path.join(BUILD, "trash"), move_aside=False)
    rmtree(APP_DIR)
    run([py, "-m", "PyInstaller", "--noconfirm", "--clean", "--log-level", "WARN",
         "--distpath", os.path.dirname(APP_DIR), "--workpath", os.path.join(BUILD, "pyi-app"), spec],
        cwd=ROOT)


def smoke_test_app() -> None:
    step("testing the program")
    cli = os.path.join(APP_DIR, "vertsheet-cli.exe")
    out = run([cli, "--version"], capture_output=True, text=True).stdout.strip()
    print("  ", out)
    demo = os.path.join(ROOT, "examples", "demo.musicxml")
    if not os.path.isfile(demo):
        run([sys.executable, os.path.join(ROOT, "examples", "make_demo.py")])
    pdf = os.path.join(BUILD, "smoke-cli.pdf")
    run([cli, demo, "-o", pdf, "-q"])
    assert os.path.getsize(pdf) > 1000, "the command line program wrote no PDF"
    pdf2 = os.path.join(BUILD, "smoke-gui.pdf")
    if os.path.exists(pdf2):
        os.remove(pdf2)
    proc = subprocess.run([os.path.join(APP_DIR, "vertSheet.exe"), "--selftest", demo, pdf2], timeout=180)
    assert proc.returncode == 0 and os.path.getsize(pdf2) > 1000, "the window program failed its self-test"
    print("   vertsheet-cli.exe and vertSheet.exe work")


def make_zip(src_dir: str, zip_path: str, prefix: str = "") -> None:
    if os.path.exists(zip_path):
        os.remove(zip_path)
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for base, _dirs, files in os.walk(src_dir):
            for f in sorted(files):
                full = os.path.join(base, f)
                rel = os.path.relpath(full, src_dir).replace("\\", "/")
                z.write(full, prefix + rel)


def build_setup(py: str, ver: str) -> str:
    step("building the installation wizard")
    payload = os.path.join(BUILD, "payload.zip")
    make_zip(APP_DIR, payload)
    ver_setup = version_file(os.path.join(BUILD, "version_setup.txt"), ver, "vertSheet Setup",
                             f"vertSheet-Setup-{ver}.exe")
    name = f"vertSheet-Setup-{ver}"
    cmd = [py, "-m", "PyInstaller", "--noconfirm", "--clean", "--log-level", "WARN", "--onefile",
           "--windowed", "--name", name, "--icon", os.path.join(ASSETS, "vertsheet.ico"),
           "--version-file", ver_setup, "--paths", ROOT,
           "--add-data", f"{payload}{os.pathsep}.",
           "--exclude-module", "unittest", "--exclude-module", "pydoc_data",
           "--distpath", DIST, "--workpath", os.path.join(BUILD, "pyi-setup"), "--specpath", BUILD]
    for f in ("vertsheet.ico", "vertsheet-64.png", "vertsheet-128.png"):
        cmd += ["--add-data", f"{os.path.join(ASSETS, f)}{os.pathsep}assets"]
    cmd.append(os.path.join(ROOT, "installer", "wizard.py"))
    run(cmd, cwd=ROOT)
    return os.path.join(DIST, name + ".exe")


def selftest_setup(setup: str) -> None:
    """Install the built setup into a sandbox, run the installed program, uninstall it."""
    step("self-test: sandboxed install > run > uninstall")
    # on the local disk like a real installation (not inside a synced folder)
    sandbox = os.path.join(tempfile.gettempdir(), "vertsheet-selftest")
    rmtree(sandbox)
    app = os.path.join(sandbox, "app")
    run([setup, "/S", f"/TESTROOT={sandbox}", f"/D={app}", "/LANG=it", "/PATH",
         f"/LOG={os.path.join(BUILD, 'selftest.log')}"], timeout=300)
    exe = os.path.join(app, "vertSheet.exe")
    for p in (exe, os.path.join(app, "vertsheet-cli.exe"), os.path.join(app, "install.json"),
              os.path.join(sandbox, "Desktop", "vertSheet.lnk"), os.path.join(sandbox, "Programs", "vertSheet.lnk")):
        assert os.path.exists(p), f"missing after install: {p}"
    sys.path.insert(0, ROOT)
    from vertsheet import winsetup as ws
    prefix = "Software\\vertSheet-selftest\\"
    assert ws.reg_get(prefix + ws.UNINSTALL_SUBKEY, "DisplayName")[0] == "vertSheet", "no uninstall entry"
    assert ws.reg_key_exists(prefix + ws.CLASSES_SUBKEY + "\\" + ws.PROGID), "no Open-with entry"
    path_value = ws.reg_get(prefix + ws.ENV_SUBKEY, "Path")[0] or ""
    assert app.lower() in path_value.lower(), "PATH entry missing"
    demo = os.path.join(ROOT, "examples", "demo.musicxml")
    pdf = os.path.join(sandbox, "installed.pdf")
    proc = subprocess.run([exe, "--selftest", demo, pdf], timeout=180)
    assert proc.returncode == 0 and os.path.isfile(pdf), "the installed program does not run"
    print("   installed program works")
    subprocess.run([exe, "--uninstall", "--quiet"], timeout=120, check=True)
    deadline = time.time() + 30
    while time.time() < deadline and os.path.exists(app):
        time.sleep(0.5)
    assert not os.path.exists(app), "the installation folder was not removed"
    for p in (os.path.join(sandbox, "Desktop", "vertSheet.lnk"), os.path.join(sandbox, "Programs", "vertSheet.lnk")):
        assert not os.path.exists(p), f"shortcut left behind: {p}"
    assert not ws.reg_key_exists(prefix + ws.UNINSTALL_SUBKEY), "uninstall entry left behind"
    assert not ws.reg_key_exists(prefix + ws.CLASSES_SUBKEY + "\\" + ws.PROGID), "Open-with entry left behind"
    assert app.lower() not in (ws.reg_get(prefix + ws.ENV_SUBKEY, "Path")[0] or "").lower(), "PATH left behind"
    ws.reg_delete_tree(prefix.rstrip("\\"))
    rmtree(sandbox)
    print("   install, shortcuts, registry, PATH and uninstall all verified")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-tests", action="store_true", help="skip the unit tests")
    ap.add_argument("--no-selftest", action="store_true", help="skip the sandboxed install test")
    args = ap.parse_args()
    if sys.platform != "win32":
        print("this script builds the Windows version; run it on Windows")
        return 1
    t0 = time.time()
    ver = version()
    if not args.no_tests:
        step("unit tests")
        run([sys.executable, "-m", "unittest", "discover", "-s", "tests"], cwd=ROOT)
    step("icon")
    run([sys.executable, os.path.join(ROOT, "tools", "make_icon.py"), ASSETS])
    os.makedirs(BUILD, exist_ok=True)
    os.makedirs(DIST, exist_ok=True)
    py = build_python()
    build_app(py, ver)
    smoke_test_app()
    setup = build_setup(py, ver)
    portable = os.path.join(DIST, f"vertSheet-{ver}-portable.zip")
    step("portable zip")
    make_zip(APP_DIR, portable, prefix="vertSheet/")
    if not args.no_selftest:
        selftest_setup(setup)
    step(f"done in {time.time() - t0:.0f} s")
    for p in (setup, portable):
        print(f"   {os.path.relpath(p, ROOT):45s} {os.path.getsize(p) / 1048576:6.1f} MB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
